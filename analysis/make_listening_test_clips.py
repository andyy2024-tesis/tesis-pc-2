"""Clips of the listening test for other listeners (repo tesis-doc-1): the same 5 s of four held-out listening
excerpts in six versions, loudness-matched, with neutral file names so the name gives nothing away.

    uv run python analysis/make_listening_test_clips.py --out ~/Documentos/tesis-doc-1

Writes <out>/public/clips/<code>.wav (24 kHz, 16-bit mono) and <out>/src/clips.ts (the excerpts, the file of each
version, and a volume-check clip from a recording that is not in the test: 276, real).

The 5 s are chosen on the real recording, clear of the excerpt's own 0.5 s fades: the window (0.1 s steps) whose
quietest 0.5 s is loudest, so no clip has a silent stretch. Each clip gets 20 ms fade-in and 100 ms fade-out, then the same integrated loudness
(ITU-R BS.1770, pyloudnorm); if any clip of an excerpt would peak above -1 dBFS, that whole excerpt is set quieter.
"""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pyloudnorm as pyln
import soundfile as sf

REPO = Path(__file__).resolve().parents[1]
AUDIO = REPO / "analysis" / "results" / "slides" / "audio"
L = "e6-structured_v12_final_learnedB"
EXCERPTS = {"023": "023_Ypswc", "176": "176_mM1wc", "277": "277_Pw1wc", "306": "306_7c1wc"}
VERSIONS = {  # test code -> listening-page file
    "real": "original",
    "ddsp": "ddsp_v5_audio",  # D2: DDSP with the same audio information
    "final": f"{L}_noise_strongD_rise",
    "final_v2": f"voc-v2_inject20-{L}_noise_strongD_rise",
    "x5": f"{L}_data100x5_noise_strongD_rise",
    "v2_100": f"voc-v2_recddsp100-{L}_data100_noise_strongD_rise",
}
SR, DUR, TARGET, PEAK = 24000, 5.0, -20.0, -1.0


def pick_segment(y):
    n, h, q = int(DUR * SR), int(0.1 * SR), int(0.5 * SR)
    best, best_s = -np.inf, 0
    for s in range(int(0.5 * SR), len(y) - n - int(0.5 * SR) + 1, h):  # stay clear of the excerpt's 0.5 s fades
        w = y[s:s + n]
        rms = [np.sqrt(np.mean(w[i:i + q] ** 2) + 1e-12) for i in range(0, n - q + 1, q // 2)]
        if min(rms) > best:
            best, best_s = min(rms), s
    return best_s


def fade(y):
    a, b = int(0.02 * SR), int(0.1 * SR)
    y = y.copy()
    y[:a] *= np.linspace(0, 1, a)
    y[-b:] *= np.linspace(1, 0, b)
    return y


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    out = Path(a.out).expanduser()
    (out / "public" / "clips").mkdir(parents=True, exist_ok=True)
    (out / "src").mkdir(parents=True, exist_ok=True)
    meter = pyln.Meter(SR)
    manifest = {"excerpts": [], "lufs": TARGET, "seconds": DUR}
    for ex, rec in EXCERPTS.items():
        real, sr = sf.read(AUDIO / rec / "original.wav")
        assert sr == SR
        s = pick_segment(real)
        clips = {v: fade(sf.read(AUDIO / rec / f"{f}.wav")[0][s:s + int(DUR * SR)]) for v, f in VERSIONS.items()}
        gains = {v: TARGET - meter.integrated_loudness(y) for v, y in clips.items()}
        peaks = {v: 20 * np.log10(np.abs(y).max()) + gains[v] for v, y in clips.items()}
        cut = max(0.0, max(peaks.values()) - PEAK)  # lower the whole excerpt if any clip would peak too high
        entry = {"id": ex, "start_s": round(s / SR, 2), "gain_cut_db": round(cut, 2), "clips": {}}
        for v, y in clips.items():
            z = y * 10 ** ((gains[v] - cut) / 20)
            code = hashlib.sha256(f"prueba-{ex}-{v}".encode()).hexdigest()[:10]
            sf.write(out / "public" / "clips" / f"{code}.wav", z, SR, subtype="PCM_16")
            entry["clips"][v] = f"{code}.wav"
            print(f"{ex} {v:9s} start {s / SR:.1f} s  LUFS {meter.integrated_loudness(z):6.1f}  "
                  f"peak {20 * np.log10(np.abs(z).max()):5.1f} dBFS")
        manifest["excerpts"].append(entry)
    # volume check: 5 s of a real recording that is not in the test
    vol, _ = sf.read(AUDIO / "276_jw1wc" / "original.wav")
    s = pick_segment(vol)
    z = fade(vol[s:s + int(DUR * SR)])
    z = z * 10 ** ((TARGET - meter.integrated_loudness(z)) / 20)
    vcode = hashlib.sha256(b"prueba-volumen").hexdigest()[:10]
    sf.write(out / "public" / "clips" / f"{vcode}.wav", z, SR, subtype="PCM_16")
    ex = [{"id": e["id"], "clips": e["clips"]} for e in manifest["excerpts"]]
    (out / "src" / "clips.ts").write_text(
        "// Generated by analysis/make_listening_test_clips.py (thesis code repo). Do not edit by hand.\n"
        f"// Same 5 s per excerpt in every version, {TARGET:g} LUFS; starts (s): "
        + ", ".join(f"{e['id']} {e['start_s']}" for e in manifest["excerpts"]) + "\n"
        f"export const VOLUME_CLIP = {json.dumps(vcode + '.wav')};\n"
        "export const EXCERPTS: { id: string; clips: Record<string, string> }[] = "
        + json.dumps(ex, indent=2) + ";\n")


if __name__ == "__main__":
    main()
